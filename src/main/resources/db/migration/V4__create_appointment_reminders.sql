-- Milestone 4: AI appointment reminders.
-- Reminders are customer notifications like confirmations and cancellations, so they reuse the
-- transactional outbox, its idempotency key (APPOINTMENT_REMINDER-appointment-<id>), and its retries.

ALTER TABLE notification_outbox DROP CONSTRAINT chk_notification_outbox_type;
ALTER TABLE notification_outbox ADD CONSTRAINT chk_notification_outbox_type
    CHECK (notification_type IN ('BOOKING_CONFIRMED', 'BOOKING_CANCELLED', 'APPOINTMENT_REMINDER'));

-- One row per reminder that was queued: which appointment, which outbox row carries it, and whether
-- the text was written by Gemini or is the clearly identified template fallback. The unique
-- constraint makes a second reminder of the same type for the same appointment impossible, whether
-- it comes from the scheduler, the manual trigger, or two runs at once, and survives restarts.
CREATE TABLE appointment_reminders (
    reminder_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT NOT NULL,
    reminder_type VARCHAR(30) NOT NULL,
    outbox_id BIGINT NOT NULL,
    content_source VARCHAR(20) NOT NULL,
    model VARCHAR(100),
    trigger_source VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_appointment_reminders UNIQUE (appointment_id, reminder_type),
    CONSTRAINT fk_appointment_reminders_appointment
        FOREIGN KEY (appointment_id) REFERENCES appointments(appointment_id),
    CONSTRAINT fk_appointment_reminders_outbox
        FOREIGN KEY (outbox_id) REFERENCES notification_outbox(outbox_id),
    CONSTRAINT chk_appointment_reminders_type CHECK (reminder_type IN ('UPCOMING_APPOINTMENT')),
    CONSTRAINT chk_appointment_reminders_source CHECK (content_source IN ('GEMINI', 'TEMPLATE')),
    CONSTRAINT chk_appointment_reminders_trigger CHECK (trigger_source IN ('SCHEDULED', 'MANUAL'))
);

CREATE INDEX idx_appointment_reminders_created ON appointment_reminders(created_at);
