-- Transactional outbox for customer notifications (Milestone 3).
-- A row is inserted in the SAME transaction as the booking or cancellation it describes, so the
-- notification exists if and only if that change committed. Delivery to the external notification
-- service happens only after commit and never rolls back the booking.

CREATE TABLE notification_outbox (
    outbox_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- One row per business event, e.g. BOOKING_CONFIRMED-appointment-42. Also sent to the
    -- notification service, which delivers each key at most once.
    idempotency_key VARCHAR(100) NOT NULL,
    appointment_id BIGINT NOT NULL,
    notification_type VARCHAR(30) NOT NULL,
    recipient_email VARCHAR(255) NOT NULL,
    recipient_name VARCHAR(200) NOT NULL,
    subject VARCHAR(200) NOT NULL,
    message VARCHAR(2000) NOT NULL,
    confirmation_number VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    attempts INT NOT NULL DEFAULT 0,
    delivery_rounds INT NOT NULL DEFAULT 0,
    last_error VARCHAR(500),
    external_notification_id VARCHAR(100),
    created_at TIMESTAMP NOT NULL,
    next_attempt_at TIMESTAMP NOT NULL,
    sent_at TIMESTAMP,
    CONSTRAINT uq_notification_outbox_key UNIQUE (idempotency_key),
    CONSTRAINT fk_notification_outbox_appointment
        FOREIGN KEY (appointment_id) REFERENCES appointments(appointment_id),
    CONSTRAINT chk_notification_outbox_type CHECK (notification_type IN ('BOOKING_CONFIRMED', 'BOOKING_CANCELLED')),
    CONSTRAINT chk_notification_outbox_status CHECK (status IN ('PENDING', 'SENT', 'FAILED')),
    CONSTRAINT chk_notification_outbox_attempts CHECK (attempts >= 0 AND delivery_rounds >= 0)
);

-- The retry job looks for PENDING rows whose next attempt is due.
CREATE INDEX idx_notification_outbox_due ON notification_outbox(status, next_attempt_at);
CREATE INDEX idx_notification_outbox_appointment ON notification_outbox(appointment_id);
